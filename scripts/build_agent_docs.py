"""Write the qex language reference that ships inside the package, src/qex/docs/, from the docs site's pages.

    python scripts/build_agent_docs.py            # rewrite src/qex/docs/
    python scripts/build_agent_docs.py OUT_DIR    # write somewhere else (the tests compare the two)

src/qex/docs/ is the language only, plain Markdown readable anywhere (an editor, GitHub, an agent reading files):

    OPERATORS.md        docs/language/reference.md: every operator, one line each, each linked to its own entry
    ops/*.md            docs/language/ops/: the families, an entry per operator
    syntax.md, ...      the other docs/language pages the entries link to

What the site does at build is done here: ```toy worked examples are evaluated on the toy data and written as
tables, `!!! note` boxes become quotes, and links to pages outside the language (the Python API) point to the site.
Never edit src/qex/docs/ by hand: edit docs/language/ and run this.
"""
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG = ROOT / "docs" / "language"
OUT = ROOT / "src" / "qex" / "docs"
SITE = "https://marketneutral.github.io/alpha-parser/"
PAGES = ["syntax.md", "concepts.md", "missing-values.md", "groups.md", "adjusted-data.md", "universes.md"]
HEADER = "<!-- Generated by scripts/build_agent_docs.py from docs/language/{src}: edit that, not this. -->\n\n"


def _toy():
    spec = importlib.util.spec_from_file_location("qex_docs_toy", ROOT / "docs" / "hooks" / "toy.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def slug(heading):
    """The anchor of a heading, as both the docs site (Python-Markdown's toc) and GitHub make it for these pages."""
    h = re.sub(r"`|<[^>]+>", "", heading).strip().lower()
    h = re.sub(r"[^\w\s-]", "", h)
    return re.sub(r"[-\s]+", "-", h).strip("-")


def toy_markdown(toy, block, info):
    """A ```toy block as Markdown tables: each expression's dates x stocks panel, as the site shows it."""
    from qex import qex, compute_context
    import pandas as pd
    o = toy._options(info)
    data = toy.DATASETS[o["data"]]()
    exprs = [l.strip() for l in block.strip().splitlines() if l.strip()]
    out = []
    for i, e in enumerate(exprs):
        with compute_context():
            v = qex(e).evaluate(data)
        dates, stocks = data["close"].index, list(data["close"].columns)
        if isinstance(v, pd.Series):
            v = pd.DataFrame({s: v for s in stocks})
        v = v.reindex(index=dates, columns=stocks)
        if o["tail"]:
            v = v.iloc[-o["tail"]:]
        cells = toy._fmt_panel(v)
        result = not o["inputs"] and i == len(exprs) - 1
        out.append(f"{'Result: ' if result else ''}`{e}`\n")
        out.append("| | " + " | ".join(stocks) + " |")
        out.append("|---|" + "---:|" * len(stocks))
        for d, row in zip(v.index, cells):
            out.append(f"| {d:%b %d} | " + " | ".join(c or "·" for c in row) + " |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def notes(text):
    """`!!! note "Title"` and its indented body as a Markdown quote."""
    def one(m):
        body = re.sub(r"^ {4}", "", m.group(2), flags=re.M).rstrip("\n")
        return f"> **{m.group(1)}**\n>\n" + "\n".join(("> " + l).rstrip() for l in body.splitlines()) + "\n\n"
    return re.sub(r'^!!! note "([^"]*)"\n((?:(?: {4}.*)?\n)+?)(?=\S|\Z)', one, text, flags=re.M)


def links(text, depth):
    """reference.md is OPERATORS.md here; pages outside docs/language/ point to the site."""
    up = "../" * depth

    def one(m):
        target = m.group(1)
        if re.match(r"[a-z]+:|#", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        parts = (Path("language") / ("ops" if depth else "") / path).as_posix().split("/")
        norm = []
        for p in parts:
            if p == "..":
                norm.pop()
            elif p not in ("", "."):
                norm.append(p)
        norm = "/".join(norm)
        if norm == "language/reference.md":
            new = f"{up}OPERATORS.md"
        elif norm.startswith("language/"):
            return m.group(0)
        else:
            new = SITE + norm[:-3] + "/"
        return f"]({new}{'#' + anchor if anchor else ''})"
    return re.sub(r"\]\(([^)\s]+)\)", one, text)


def render(text, toy, depth):
    text = re.sub(r"^```toy([^\n]*)\n(.*?)^```\s*$", lambda m: toy_markdown(toy, m.group(2), m.group(1).strip()),
                  text, flags=re.S | re.M)
    return links(notes(text), depth)


def entries():
    """{operator: 'ops/<page>.md#<anchor>'}: the entry whose heading is the operator, or whose signature line shows it
    (close's entry is also open's, high's and low's)."""
    out = {}
    for page in sorted((LANG / "ops").glob("*.md")):
        heading = None
        for line in page.read_text().splitlines():
            m = re.match(r"#{2,4} (.+)$", line)
            if m:
                heading = m.group(1).strip()
                name = heading.strip("`")
                if re.fullmatch(r"[a-z_0-9]+", name):
                    out.setdefault(name, f"ops/{page.name}#{slug(heading)}")
            elif heading and line.startswith('<p class="sig">'):
                for name in re.findall(r"<code>([a-z_0-9]+)\(", line):
                    out.setdefault(name, f"ops/{page.name}#{slug(heading)}")
    return out


def operators(text):
    """reference.md with each operator's row linked to its entry."""
    where = entries()

    def row(m):
        name = m.group(2)
        if name not in where:
            raise SystemExit(f"{name} has a reference line but no entry in docs/language/ops/")
        return f"| [`{m.group(1)}`]({where[name]}) |"
    return re.sub(r"^\| `(([a-z_0-9]+)(?:\([^`]*\))?)` \|", row, text, flags=re.M)


def build(out=OUT):
    toy = _toy()
    out = Path(out)
    (out / "ops").mkdir(parents=True, exist_ok=True)
    written = {}
    ref = render(operators((LANG / "reference.md").read_text()), toy, 0)
    written["OPERATORS.md"] = HEADER.format(src="reference.md") + ref
    for p in PAGES:
        written[p] = HEADER.format(src=p) + render((LANG / p).read_text(), toy, 0)
    for p in sorted((LANG / "ops").glob("*.md")):
        written[f"ops/{p.name}"] = HEADER.format(src=f"ops/{p.name}") + render(p.read_text(), toy, 1)
    for rel, text in written.items():
        (out / rel).write_text(text)
    return written


if __name__ == "__main__":
    w = build(sys.argv[1] if len(sys.argv) > 1 else OUT)
    print(f"wrote {len(w)} pages to {sys.argv[1] if len(sys.argv) > 1 else OUT}")
